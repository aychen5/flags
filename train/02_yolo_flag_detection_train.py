def parse_xml(xml_file):
    records = []

    for box in xml_file.find_all('box'):
        img = box.find_parent('image')
        rec = {
            "parent_tag": "box",
            "class": 0,  # single-class "flag"
            "id": img.get("id"),
            "filename": img.get("name"),
            "xtl": float(box.get("xtl")),
            "ytl": float(box.get("ytl")),
            "xbr": float(box.get("xbr")),
            "ybr": float(box.get("ybr")),
        }
        records.append(rec)

    # images without any <box>
    for img in xml_file.find_all('image'):
        if not img.find('box'):  # no boxes under this image
            records.append({
                "parent_tag": "image",
                "class": None,
                "id": img.get("id"),
                "filename": img.get("name"),
                "xtl": None, "ytl": None, "xbr": None, "ybr": None
            })
    return pd.DataFrame.from_records(records)\

def id_to_url_tf(img_id_tf: tf.Tensor, resolution=2048) -> tf.Tensor:
    def _py(id_in):
        img_id = id_in.numpy().decode("utf-8")
        try:
            url = mly.interface.image_thumbnail(image_id=img_id, resolution=resolution)
            return url.encode("utf-8")
        except Exception:
            return b""
    return tf.py_function(_py, [img_id_tf], Tout=tf.string)

def url_to_uint8_tf(url_tf: tf.Tensor) -> tf.Tensor:
    def _py(url_bytes):
        url = url_bytes.numpy().decode("utf-8")
        if not url:
            return np.zeros((8,8,3), np.uint8)
        with requests.get(url, stream=True, timeout=30) as r:
            #r.raise_for_status()
            buf = BytesIO(r.content)
        img = Image.open(buf).convert("RGB")
        return np.array(img, dtype=np.uint8)
    img = tf.py_function(_py, [url_tf], Tout=tf.uint8)
    img.set_shape([None, None, 3])
    return img

def _normalize_boxes_xyxy(boxes, image):
    # image is (H,W,3)
    h = tf.cast(tf.shape(image)[0], tf.float32)
    w = tf.cast(tf.shape(image)[1], tf.float32)
    scale = tf.stack([w, h, w, h])  # (4,)

    if isinstance(boxes, tf.RaggedTensor):
        fv = boxes.flat_values
        # Guarantee 2D [num_boxes, 4] before division
        fv = tf.reshape(fv, [-1, 4])              # <-- key line
        fv = fv / scale
        boxes = boxes.with_flat_values(fv)        # preserves row_splits
    else:
        boxes = boxes / scale                     # (..., 4) dense is fine
    return boxes

def load_dataset(image_id, classes, bbox, normalize = False):
    # Read Image
    url_tf = id_to_url_tf(image_id)            # tf.string
    image = url_to_uint8_tf(url_tf)
    image.set_shape([None, None, 3])
    classes = tf.cast(classes, tf.int32)
    boxes    = tf.cast(bbox,   tf.float32)     # stays ragged if input is ragged

    # inline normalize: (only for dense)
    if normalize:
      boxes = _normalize_boxes_xyxy(boxes, image)

    bounding_boxes = {"classes": classes, "boxes": boxes}
    return {"images": image, "bounding_boxes": bounding_boxes}

# another helper for kerasCV which expects tuples; (images, dense_box_dict)
def dict_to_tuple(sample):
  images = sample["images"]
  bbox   = sample["bounding_boxes"]
  dense = keras_cv.bounding_box.to_dense(
      {"boxes": bbox["boxes"], "classes": bbox["classes"]}  # only numeric fields
  )
  return images, dense

