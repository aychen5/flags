def id_to_url_tf(img_id_tf: tf.Tensor, resolution=1024) -> tf.Tensor:
    def _py(id_in):
        img_id = id_in.numpy().decode("utf-8")
        try:
            url = mly.interface.image_thumbnail(image_id=img_id, resolution=resolution)
            return url.encode("utf-8")
        except Exception:
            return b""
    return tf.py_function(_py, [img_id_tf], Tout=tf.string)

def url_to_uint8_tf(url_tf: tf.Tensor) -> tf.Tensor:
    def _py(url_bytes):
        url = url_bytes.numpy().decode("utf-8")
        if not url:
            return np.zeros((8,8,3), np.uint8)
        with requests.get(url, stream=True, timeout=30) as r:
            #r.raise_for_status()
            buf = io.BytesIO(r.content)
        img = Image.open(buf).convert("RGB")
        return np.array(img, dtype=np.uint8)
    img = tf.py_function(_py, [url_tf], Tout=tf.uint8)
    img.set_shape([None, None, 3])
    return img

def visualize_batch(imgs, boxes, classes, scores, image_ids, min_conf=0.5, max_dets=None):
    """
    imgs:    (B,H,W,3) float32 in [0,1]  (your resized, letterboxed batch)
    boxes:   (B,N,4)   xyxy
    classes: (B,N)     int
    scores:  (B,N)     float
    image_ids: (B)       str
    """
    B = imgs.shape[0]
    H, W = imgs.shape[1], imgs.shape[2]

    nrows, ncols = 4, 4
    fig, axes = plt.subplots(nrows, ncols,
                             #figsize=(12, 12),
                             figsize=(ncols*6, nrows*6),
                             constrained_layout=True)
    axes = axes.flatten()

    for i in range(B):
      im = (imgs[i].numpy() ).astype("uint8") if isinstance(imgs[i], tf.Tensor) else (imgs[i]).astype("uint8")
      ax = axes[i]
      ax.imshow(im)
      ax.axis("off")

      #label the image
      ax.set_title(image_ids[i], fontsize=8)

      num_drawn = 0
      for (x1, y1, x2, y2), cls, sc in zip(boxes[i], classes[i], scores[i]):
          sc = float(sc)
          if sc < min_conf:
              continue
          # Skip completely empty/padded boxes if any
          if (x2 - x1) <= 1 or (y2 - y1) <= 1:
              continue

          ax.add_patch(patches.Rectangle(
              (x1, y1), x2 - x1, y2 - y1,
              linewidth=2, edgecolor='r', facecolor='none'
          ))
          label_txt = CLASS_NAMES[int(cls)] if (CLASS_NAMES is not None and int(cls) < len(CLASS_NAMES)) else str(int(cls))
          ax.text(x1, max(y1-3, 0), f"{label_txt} {sc:.2f}",
                  fontsize=10, color='yellow', bbox=dict(facecolor='black', alpha=0.4, pad=1))

          num_drawn += 1
          if max_dets is not None and num_drawn >= max_dets:
              break

    plt.show()
    plt.close(fig)

