inference_ds = (
    tf.data.Dataset.from_tensor_slices(image_ids)                              # id
      .map(lambda img_id: (img_id, id_to_url_tf(img_id)), num_parallel_calls=4)  # (id, url)
      .map(lambda img_id, url: (url_to_uint8_tf(url), img_id), num_parallel_calls=4)  # (img, id)
      .map(lambda img, img_id: (tf.cast(img, tf.float32), img_id), num_parallel_calls=tf.data.AUTOTUNE)
      .map(lambda imgs, ids: (resizer({"images": imgs})["images"], ids), num_parallel_calls=tf.data.AUTOTUNE)
      .batch(16)
      .prefetch(tf.data.AUTOTUNE)
)

